#!/usr/bin/env python3
"""Synthetic Bell-202/AX.25 NRZI fixture; no claim of an RF capture."""
from pathlib import Path

def address(call, ssid, last):
    return bytes(ord(c) << 1 for c in call.ljust(6)) + bytes([0x60 | ssid << 1 | last])
def fixture(payload):
    frame = address('APRS', 0, 0) + address('N0CALL', 15, 1) + b'\x03\xf0' + payload
    crc = 0xffff
    for byte in frame:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ (0x8408 if crc & 1 else 0)
    frame += (crc ^ 0xffff).to_bytes(2, 'little')
    # Continuous stuffing must span byte boundaries.
    raw = [int(c) for c in '01111110'] * 4
    ones = 0
    for byte in frame:
        for bit in range(8):
            value = (byte >> bit) & 1
            raw.append(value)
            ones = ones + 1 if value else 0
            if ones == 5:
                raw.append(0)
                ones = 0
    raw += [int(c) for c in '01111110'] * 240
    capture = bytearray(240)
    level = 0
    for i, bit in enumerate(raw[:1920]):
        if not bit:
            level ^= 1
        capture[i // 8] |= level << (7 - i % 8)
    return capture

output = "/* Synthetic fixtures generated by tests/make_capture.py. */\n"
for name, payload in (("capture_fixture", b"!4903.50N/07201.75W-Test"),
                      ("message_fixture", b":MYCALL   :MEET AT TRAILHEAD{01")):
    capture = fixture(payload)
    output += "static const unsigned char " + name + "[240] = {\n"
    output += "\n".join(",".join(f"0x{x:02x}" for x in capture[i:i+16]) + "," for i in range(0,240,16)) + "\n};\n"
Path(__file__).with_name("capture.h").write_text(output)
